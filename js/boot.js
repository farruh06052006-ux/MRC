/* ============================================================
   MRC — подключается в <head>, до разметки страницы.

   Картинки могут не загрузиться раньше, чем выполнится main.js,
   а их onerror вызывает imgFallback. Поэтому функция объявлена
   здесь: к моменту первой ошибки загрузки она уже существует.
   ============================================================ */

function imgFallback(img) {
  img.style.display = 'none';
  var frame = img.closest('.frame');
  if (frame) frame.classList.add('is-ph');
}
